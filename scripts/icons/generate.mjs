const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const marker = '// @generated by scripts/icons/generate.mjs; do not edit.';
export const sha256 = (bytes) => createHash('sha256').update(bytes).digest('hex');
export function artworkHash(value) {
  const canonical = (item) =>
    Array.isArray(item)
      ? item.map(canonical)
      : item && typeof item === 'object'
        ? Object.fromEntries(
            Object.keys(item)
              .sort()
              .map((key) => [key, canonical(item[key])]),
          )
        : item;
  return sha256(JSON.stringify(canonical(value)));
}
const order = (a, b) => (a < b ? -1 : a > b ? 1 : 0);
const primitives = new Set(['path', 'circle', 'ellipse', 'g', 'defs', 'use']);
const attributes = new Set([
  'd',
  'opacity',
  'fillOpacity',
  'cx',
  'cy',
  'r',
  'rx',
  'ry',
  'fillRule',
  'id',
  'xlinkHref',
  'overflow',
  'transform',
]);

function syntax(source, file) {
  return parseSync(source, {
    filename: file,
    configFile: false,
    babelrc: false,
    parserOpts: { sourceType: 'module' },
  }).program;
}
function literal(node, file) {
  if (node?.type === 'StringLiteral' || node?.type === 'NumericLiteral') return node.value;
  if (
    node?.type === 'UnaryExpression' &&
    node.operator === '-' &&
    node.argument.type === 'NumericLiteral'
  )
    return -node.argument.value;
  throw Error('Unsupported icon attribute in ' + file);
}
export function parseIcon(source, name) {
  const file = name + '.mjs',
    ast = syntax(source, file),
    factories = new Set(),
    jsx = new Set(),
    fragments = new Set(),
    react = new Set();
  let exported;
  for (const directive of ast.directives)
    if (directive.value.value !== 'use client')
      throw Error('Unsupported icon directive in ' + file);
  for (const statement of ast.body) {
    if (statement.type === 'ImportDeclaration') {
      const from = statement.source.value;
      if (
        from === './utils/createSvgIcon.mjs' &&
        statement.specifiers.length === 1 &&
        statement.specifiers[0].type === 'ImportDefaultSpecifier'
      )
        factories.add(statement.specifiers[0].local.name);
      else if (
        from === 'react' &&
        statement.specifiers.length === 1 &&
        statement.specifiers[0].type === 'ImportNamespaceSpecifier'
      )
        react.add(statement.specifiers[0].local.name);
      else if (from === 'react/jsx-runtime') {
        for (const item of statement.specifiers) {
          if (item.type !== 'ImportSpecifier')
            throw Error('Unsupported JSX runtime import in ' + file);
          if (item.imported.name === 'jsx' || item.imported.name === 'jsxs')
            jsx.add(item.local.name);
          else if (item.imported.name === 'Fragment') fragments.add(item.local.name);
          else throw Error('Unsupported JSX runtime import in ' + file);
        }
      } else throw Error('Unsupported icon import in ' + file);
    } else if (statement.type === 'ExportDefaultDeclaration' && !exported)
      exported = statement.declaration;
    else throw Error('Unsupported icon statement in ' + file);
  }
  if (
    exported?.type !== 'CallExpression' ||
    !factories.has(exported.callee.name) ||
    exported.arguments.length !== 2 ||
    literal(exported.arguments[1], file) !== name
  )
    throw Error('Icon factory/name mismatch: ' + file);
  const visit = (node) => {
    if (node.type === 'ArrayExpression')
      return { type: '#array', props: {}, children: node.elements.map(visit) };
    if (
      node.type !== 'CallExpression' ||
      !jsx.has(node.callee.name) ||
      ![2, 3].includes(node.arguments.length)
    )
      throw Error('Unsupported SVG expression in ' + file);
    const [tag, options] = node.arguments;
    const type =
      tag.type === 'StringLiteral'
        ? tag.value
        : fragments.has(tag.name) ||
            (tag.type === 'MemberExpression' &&
              !tag.computed &&
              react.has(tag.object.name) &&
              tag.property.name === 'Fragment')
          ? '#fragment'
          : null;
    if (type !== '#fragment' && !primitives.has(type))
      throw Error('Missing native SVG primitive in ' + file);
    if (options.type !== 'ObjectExpression') throw Error('Unsupported SVG props in ' + file);
    const props = {},
      children = [];
    for (const property of options.properties) {
      if (
        property.type !== 'ObjectProperty' ||
        property.computed ||
        property.key.type !== 'Identifier'
      )
        throw Error('Unsupported SVG property in ' + file);
      const key = property.key.name;
      if (key === 'children') {
        const nodes =
          property.value.type === 'ArrayExpression' ? property.value.elements : [property.value];
        children.push(...nodes.map(visit));
      } else {
        if (!attributes.has(key) || Object.hasOwn(props, key))
          throw Error('Unsupported/duplicate SVG attribute in ' + file + ': ' + key);
        props[key] = literal(property.value, file);
      }
    }
    return {
      type,
      props,
      children,
      ...(node.arguments.length === 3 ? { key: literal(node.arguments[2], file) } : {}),
    };
  };
  return visit(exported.arguments[0]);
}

export async function loadCatalog(directory = root) {
  const state = JSON.parse(await readFile(resolve(directory, 'upstream/state.json'), 'utf8'));
  const reference = state.packages['@mui/icons-material'].baseline;
  if (reference.version !== '9.5.0' || reference.license !== 'MIT' || reference.licenseReview)
    throw Error('An explicitly reviewed icon baseline is required');
  const archivePath = resolve(
    directory,
    '.cache/upstream/icons-material-' + reference.version + '.tgz',
  );
  const bytes = await readFile(archivePath);
  if ('sha512-' + createHash('sha512').update(bytes).digest('base64') !== reference.integrity)
    throw Error('Icon archive integrity mismatch');
  const archive = JSON.parse(
    execFileSync('python3', [resolve(root, 'scripts/icons/read-archive.py'), archivePath], {
      encoding: 'utf8',
      maxBuffer: 128 * 1024 * 1024,
    }),
  );
  if (
    archive.manifest.name !== '@mui/icons-material' ||
    archive.manifest.version !== reference.version ||
    archive.manifest.license !== 'MIT'
  )
    throw Error('Icon package identity mismatch');
  if (sha256(archive.license) !== reference.licenseSha256) throw Error('Icon license mismatch');
  const snapshot = await readFile(resolve(directory, reference.apiSnapshot), 'utf8');
  if (
    sha256(snapshot) !== reference.apiSnapshotSha256 ||
    JSON.stringify(archive.declarations) !== JSON.stringify(JSON.parse(snapshot))
  )
    throw Error('Icon declaration snapshot mismatch');
  const names = [],
    modules = new Map();
  for (const statement of syntax(archive.files['index.mjs'], 'index.mjs').body) {
    if (
      statement.type !== 'ExportNamedDeclaration' ||
      statement.specifiers.length !== 1 ||
      statement.specifiers[0].type !== 'ExportSpecifier'
    )
      throw Error('Unexpected icon barrel statement');
    const item = statement.specifiers[0],
      name = item.exported.name;
    if (
      item.local.name !== 'default' ||
      statement.source?.value !== './' + name + '.mjs' ||
      !/^[A-Z][A-Za-z0-9]*$/.test(name) ||
      modules.has(name)
    )
      throw Error('Unexpected icon export: ' + name);
    const source = archive.files[name + '.mjs'];
    if (
      !source ||
      !archive.files[name + '.js'] ||
      !archive.files[name + '.d.ts'] ||
      !archive.files[name + '.d.mts']
    )
      throw Error('Incomplete icon module: ' + name);
    if (archive.files[name + '.d.ts'].trim() !== "export { default } from '@mui/material/SvgIcon';")
      throw Error('Unexpected icon declaration: ' + name);
    names.push(name);
    modules.set(name, { artwork: parseIcon(source, name), source });
  }
  const physical = Object.keys(archive.files)
    .filter((file) => /^[A-Za-z0-9_$]+\.mjs$/.test(file) && file !== 'index.mjs')
    .map((file) => file.slice(0, -4))
    .sort(order);
  if (JSON.stringify([...names].sort(order)) !== JSON.stringify(physical))
    throw Error('Icon root exports and physical modules disagree');
  const styles = ['Outlined', 'Rounded', 'Sharp', 'TwoTone'];
  const completeFiveStyleStems = names.filter((name) =>
    styles.every((suffix) => modules.has(name + suffix)),
  ).length;
  const suffixCounts = Object.fromEntries(
    ['Unsuffixed', ...styles].map((style) => [
      style,
      names.filter((name) =>
        style === 'Unsuffixed'
          ? !styles.some((suffix) => name.endsWith(suffix))
          : name.endsWith(style),
      ).length,
    ]),
  );
  return {
    reference,
    archive,
    archiveSha256: sha256(bytes),
    names,
    modules,
    completeFiveStyleStems,
    suffixCounts,
  };
}

function element(node) {
  if (node.type === '#array') return '[' + node.children.map(element).join(', ') + ']';
  const props = { ...node.props, ...(node.key === undefined ? {} : { key: node.key }) };
  const type = node.type === '#fragment' ? 'React.Fragment' : JSON.stringify(node.type);
  return (
    '/*#__PURE__*/React.createElement(' +
    type +
    ', ' +
    (Object.keys(props).length ? JSON.stringify(props) : 'null') +
    node.children.map((child) => ', ' + element(child)).join('') +
    ')'
  );
}
export function iconSource(name, artwork) {
  return `${marker}\n/* @mui/icons-material 9.5.0/${name}.mjs; wrapper Copyright (c) 2014 Call-Em-All.\n * Google Material Icons artwork. Geometry unchanged; native factory/import adaptation.\n * See LICENSE, NOTICE, THIRD_PARTY_NOTICES.md and LICENSE.material-icons. */\nimport React from 'react';\nimport createSvgIcon from '../utils/createSvgIcon';\nconst Icon = /*#__PURE__*/createSvgIcon(${element(artwork)}, ${JSON.stringify(name)});\nexport default Icon;\nexport { Icon as ${name} };\n`;
}
async function save(directory, path, content, check) {
  const full = resolve(directory, path);
  let current;
  try {
    current = await readFile(full, 'utf8');
  } catch (error) {
    if (error.code !== 'ENOENT') throw error;
  }
  if (current === content) return;
  if (check) throw Error('Generated icon output changed: ' + path);
  await mkdir(dirname(full), { recursive: true });
  await writeFile(full, content);
}
export async function generateIcons({ directory = root, check = false } = {}) {
  const catalog = await loadCatalog(directory),
    { names, modules, reference } = catalog;
  const glyphLicense = {
    license: 'Apache-2.0',
    source: 'https://raw.githubusercontent.com/google/material-design-icons/master/LICENSE',
    file: 'packages/icons/LICENSE.material-icons',
    sha256: '58d1e17ffe5109a7ae296caafcadfdbe6a7d176f0bc4ab01e12a689b0499d8bd',
  };
  if (sha256(await readFile(resolve(directory, glyphLicense.file))) !== glyphLicense.sha256)
    throw Error('Retained Google glyph license mismatch');
  const files = new Map();
  for (const name of names)
    files.set(`packages/icons/src/${name}/index.ts`, iconSource(name, modules.get(name).artwork));
  files.set(
    'packages/icons/src/index.ts',
    `${marker}\nexport { SvgIcon } from '@altroo/mui-native/SvgIcon';\nexport type { SvgIconProps, SvgIconHandle, SvgIconOwnProps, SvgIconPropsSizeOverrides, SvgIconPropsColorOverrides } from '@altroo/mui-native/SvgIcon';\nexport { createSvgIcon } from './createSvgIcon';\n` +
      names.map((name) => `export { default as ${name} } from './${name}';\n`).join(''),
  );
  files.set('packages/icons/src/index/index.ts', `${marker}\nexport * from '../index';\n`);
  files.set(
    'packages/icons/src/createSvgIcon.ts',
    `${marker}\nimport React from 'react';\nimport { Path } from 'react-native-svg';\nimport { createSvgIcon as createMaterialSvgIcon } from '@altroo/mui-native/utils/createSvgIcon';\n/** Early path-string extension retained independently of generated glyphs. */\nexport function createSvgIcon(path: React.ReactNode, displayName: string) {\n  return createMaterialSvgIcon(typeof path === 'string' ? React.createElement(Path, { d: path }) : path, displayName);\n}\n`,
  );
  files.set(
    'packages/icons/src/utils/createSvgIcon/index.ts',
    `${marker}\nexport { createSvgIcon as default, createSvgIcon } from '@altroo/mui-native/utils/createSvgIcon';\n`,
  );
  const manifest = JSON.parse(
    await readFile(resolve(directory, 'packages/icons/package.json'), 'utf8'),
  );
  manifest.module = './dist/esm/index.mjs';
  manifest.exports = {
    '.': {
      types: './dist/index.d.ts',
      'react-native': './src/index.ts',
      import: './dist/esm/index.mjs',
      require: './dist/index.js',
      default: './dist/index.js',
    },
    './package.json': './package.json',
    './*': {
      types: './dist/*/index.d.ts',
      'react-native': './src/*/index.ts',
      import: './dist/esm/*/index.mjs',
      require: './dist/*/index.js',
      default: './dist/*/index.js',
    },
  };
  manifest.files = [
    ...new Set([...manifest.files, 'THIRD_PARTY_NOTICES.md', 'LICENSE.material-icons']),
  ];
  files.set('packages/icons/package.json', JSON.stringify(manifest, null, 2) + '\n');
  const supported = JSON.parse(
    await readFile(resolve(directory, 'packages/compat/supported.json'), 'utf8'),
  );
  supported['@mui/icons-material'].subpaths = [...names, 'index', 'utils/createSvgIcon'];
  files.set('packages/compat/supported.json', JSON.stringify(supported, null, 2) + '\n');
  const formatting = await resolveConfig(resolve(directory, '.prettierrc.json'));
  for (const [path, source] of files)
    files.set(path, await format(source, { ...formatting, filepath: path }));
  const sourceFiles = {},
    generated = {},
    artworkHashes = {};
  for (const name of names) {
    artworkHashes[name] = artworkHash({ name, path: modules.get(name).artwork });
    for (const ext of ['mjs', 'js', 'd.ts', 'd.mts'])
      sourceFiles[name + '.' + ext] = sha256(catalog.archive.files[name + '.' + ext]);
  }
  for (const file of [
    'index.mjs',
    'index.js',
    'index.d.ts',
    'index.d.mts',
    'utils/createSvgIcon.mjs',
    'utils/createSvgIcon.js',
  ])
    sourceFiles[file] = sha256(catalog.archive.files[file]);
  for (const [path, source] of files)
    if (path.startsWith('packages/icons/src/')) generated[path] = sha256(source);
  const generatorSources = {};
  for (const path of ['scripts/icons/generate.mjs', 'scripts/icons/read-archive.py'])
    generatorSources[path] = sha256(await readFile(resolve(directory, path)));
  files.set(
    'upstream/material-icons.json',
    JSON.stringify(
      {
        schemaVersion: 1,
        description:
          'Deterministic native modules from the complete pinned Material Icons catalog; catalog/artwork coverage does not certify native visual or accessibility parity.',
        reference: {
          name: '@mui/icons-material',
          ...reference,
          archiveSha256: catalog.archiveSha256,
        },
        glyphLicense,
        counts: {
          icons: names.length,
          completeFiveStyleStems: catalog.completeFiveStyleStems,
          namesBySuffix: catalog.suffixCounts,
        },
        primitives: [...primitives],
        sourceFiles,
        artworkHashes,
        generatorSources,
        generated,
      },
      null,
      2,
    ) + '\n',
  );
  files.set(
    'upstream/material-icons.json',
    await format(files.get('upstream/material-icons.json'), { ...formatting, parser: 'json' }),
  );
  // Remove only obsolete generated glyph files, preserving authored helpers.
  for (const entry of await readdir(resolve(directory, 'packages/icons/src'), {
    withFileTypes: true,
  })) {
    if (!entry.isDirectory() || !/^[A-Z]/.test(entry.name) || modules.has(entry.name)) continue;
    const path = `packages/icons/src/${entry.name}/index.ts`;
    if ((await readFile(resolve(directory, path), 'utf8')).startsWith(marker)) {
      if (check) throw Error('Obsolete generated icon: ' + path);
      await unlink(resolve(directory, path));
    }
  }
  for (const [path, source] of files) await save(directory, path, source, check);
  return {
    icons: names.length,
    completeFiveStyleStems: catalog.completeFiveStyleStems,
    archiveSha256: catalog.archiveSha256,
    licenseSha256: reference.licenseSha256,
  };
}
if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const args = process.argv.slice(2);
  if (args.some((arg) => arg !== '--check') || args.length > 1)
    throw Error('Use generate.mjs [--check]');
  console.log(JSON.stringify(await generateIcons({ check: args.includes('--check') }), null, 2));
}
